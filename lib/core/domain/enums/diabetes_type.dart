/// Classifies the medical category of diabetes mellitus diagnosed for the user.
enum DiabetesType {
  /// Type 1 diabetes (autoimmune destruction of insulin-producing beta cells).
  type1,

  /// Type 2 diabetes (progressive loss of adequate beta-cell insulin secretion).
  type2,

  /// Gestational diabetes (diagnosed during pregnancy).
  gestational,

  /// Latent Autoimmune Diabetes in Adults (slow-progressing autoimmune diabetes).
  lada,
}
